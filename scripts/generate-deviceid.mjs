// Generates src/deviceid-data.ts from the APRS device identification database
// (https://github.com/aprsorg/aprs-deviceid), CC BY-SA 2.0, maintained by Hessu, OH7LZB.
// Contact addresses are left out; nothing else is changed.
//
//   node scripts/generate-deviceid.mjs <path to aprs-deviceid checkout>
//
// Needs the `yaml` dev dependency. Writes the commit the data came from into the module.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parse } from 'yaml';

const source = resolve(process.argv[2] ?? '../M0LTE.Aprs/.research/aprs-deviceid');
const doc = parse(readFileSync(join(source, 'tocalls.yaml'), 'utf8'));
const git = (...args) => execFileSync('git', ['-C', source, ...args], { encoding: 'utf8' }).trim();
const commit = git('rev-parse', 'HEAD');
const date = git('log', '-1', '--format=%cs');

const KEEP = ['vendor', 'model', 'class', 'os', 'features'];
function device(entry) {
  const out = {};
  for (const key of KEEP) if (entry[key] !== undefined) out[key] = key === 'features' ? [...entry[key]] : String(entry[key]);
  return out;
}

const tocalls = doc.tocalls.map((e) => ({ tocall: String(e.tocall), ...device(e) }));
const mice = doc.mice.map((e) => ({ suffix: String(e.suffix), ...device(e) }));
const legacy = doc.micelegacy.map((e) => ({
  prefix: String(e.prefix),
  ...(e.suffix !== undefined ? { suffix: String(e.suffix) } : {}),
  ...device(e),
}));
const classes = doc.classes.map((e) => ({ class: String(e.class), shown: String(e.shown), description: String(e.description) }));

const json = (v) => JSON.stringify(v, null, 2);
const out = `// Generated by scripts/generate-deviceid.mjs from the APRS device identification database,
// https://github.com/aprsorg/aprs-deviceid (commit ${commit.slice(0, 8)}, ${date}), maintained by
// Hessu, OH7LZB, and licensed under CC BY-SA 2.0 (see THIRD-PARTY-NOTICES.md). Contact addresses
// are left out; nothing else is changed. Do not edit by hand.

/* eslint-disable */

/** Where this data came from. */
export const DEVICEID_SOURCE = { repository: 'https://github.com/aprsorg/aprs-deviceid', commit: '${commit}', date: '${date}' } as const;

export interface DeviceEntry {
  readonly vendor?: string;
  readonly model?: string;
  readonly class?: string;
  readonly os?: string;
  readonly features?: readonly string[];
}

/** Destination (tocall) patterns: \`?\` one character, \`*\` anything, \`n\` a digit. */
export const TOCALLS: readonly (DeviceEntry & { readonly tocall: string })[] = ${json(tocalls)};

/** New-style Mic-E two-character suffixes (after a \`\\\`\` or \`'\` type code). */
export const MICE: readonly (DeviceEntry & { readonly suffix: string })[] = ${json(mice)};

/** Legacy (Kenwood) Mic-E prefix and suffix. */
export const MICE_LEGACY: readonly (DeviceEntry & { readonly prefix: string; readonly suffix?: string })[] = ${json(legacy)};

/** Device classes. */
export const DEVICE_CLASSES: readonly { readonly class: string; readonly shown: string; readonly description: string }[] = ${json(classes)};
`;
writeFileSync(new URL('../src/deviceid-data.ts', import.meta.url), out);
console.log(`src/deviceid-data.ts: ${tocalls.length} tocalls, ${mice.length} Mic-E suffixes, ${legacy.length} legacy, from ${commit.slice(0, 8)} (${date})`);
